import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const output = path.join(root, "data", "packageMedia.ts");
const MAX_PACKAGE_PHOTOS = 10;

// Package photos are extension-flexible. Filenames are unrestricted.
const imageExtensions = new Set([
  ".jpg", ".jpeg", ".jpe", ".jfif", ".png", ".webp", ".avif", ".gif",
  ".bmp", ".dib", ".tif", ".tiff", ".svg", ".ico", ".heic", ".heif", ".jxl",
]);

function walk(dir, relative = "") {
  if (!fs.existsSync(dir)) return [];
  const result = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const absolute = path.join(dir, entry.name);
    const rel = path.posix.join(relative, entry.name);
    if (entry.isDirectory()) result.push(...walk(absolute, rel));
    else if (imageExtensions.has(path.extname(entry.name).toLowerCase())) result.push(rel);
  }
  return result;
}

const grouped = {};

function addRoot(mediaRoot, folderPrefix, publicPrefix) {
  const files = walk(mediaRoot).sort((a, b) => a.localeCompare(b));
  for (const file of files) {
    const folder = path.posix.join(folderPrefix, path.posix.dirname(file));
    if (!grouped[folder]) grouped[folder] = [];
    if (grouped[folder].length < MAX_PACKAGE_PHOTOS) {
      grouped[folder].push(`${publicPrefix}/${file}`);
    }
  }
}

// Existing package media lives under public/images/packages.
addRoot(path.join(root, "public", "images", "packages"), "", "/images/packages");

// New package uploads may live directly under public/images/<state>/<package-slug>.
// This includes Lakshadweep and keeps arbitrary JPG/PNG/WEBP/AVIF filenames working.
addRoot(path.join(root, "public", "images", "lakshadweep"), "lakshadweep", "/images/lakshadweep");

// Multi-State packages use dedicated package slugs but their source photos
// currently live in the closest matching existing package folders.
const mediaAliases = {
  "multi-state/varanasi-ayodhya-prayagraj-gaya-bodh-gaya": "uttar-pradesh/varanasi-prayagraj-ayodhya",
  "multi-state/varanasi-ayodhya-prayagraj-gaya-bodh-gaya-deoghar": "bihar/bihar-buddhist-circuit",
  "multi-state/delhi-agra-jaipur-golden-triangle": "delhi/delhi-agra-jaipur",
};

for (const [alias, source] of Object.entries(mediaAliases)) {
  if (grouped[source]?.length) grouped[alias] = [...grouped[source]];
}

const content = `// AUTO-GENERATED by scripts/generate-package-media.mjs. Do not edit manually.\nexport const packageMedia: Record<string, string[]> = ${JSON.stringify(grouped, null, 2)};\n`;
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, content, "utf8");
console.log(`Package media manifest generated: maximum ${MAX_PACKAGE_PHOTOS} image(s) per package folder.`);
