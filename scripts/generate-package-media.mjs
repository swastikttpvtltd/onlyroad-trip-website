import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const root = process.cwd();
const mediaRoot = path.join(root, "public", "images", "packages");
const output = path.join(root, "data", "packageMedia.ts");

// Package images are discovered by their actual image data, not by a fixed
// filename extension or a fixed number of files. This allows JPG, JPEG, AVIF,
// WebP, PNG and other image formats that Sharp can read.
async function walk(dir, relative = "") {
  if (!fs.existsSync(dir)) return [];
  const result = [];

  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const absolute = path.join(dir, entry.name);
    const rel = path.posix.join(relative, entry.name);

    if (entry.isDirectory()) {
      result.push(...(await walk(absolute, rel)));
      continue;
    }

    try {
      const metadata = await sharp(absolute, { animated: false }).metadata();
      if (metadata.width && metadata.height) result.push(rel);
    } catch {
      // Ignore non-image files such as README/TXT placeholders.
    }
  }

  return result;
}

// Package data uses URL-safe lowercase slugs, while the actual folders in
// public/images/packages may use capitals, spaces, underscores or mixed case.
// Normalize only the manifest key; keep the real file path unchanged.
function normalizeSegment(value) {
  return value
    .trim()
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function normalizePackageKey(folder) {
  return folder
    .split("/")
    .map(normalizeSegment)
    .filter(Boolean)
    .join("/");
}

const imageSort = (a, b) => {
  const aName = path.posix.basename(a).replace(/\.[^.]+$/, "").toLowerCase();
  const bName = path.posix.basename(b).replace(/\.[^.]+$/, "").toLowerCase();
  const aIsHero = aName === "hero";
  const bIsHero = bName === "hero";

  if (aIsHero && !bIsHero) return -1;
  if (!aIsHero && bIsHero) return 1;
  return a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" });
};

async function main() {
  const files = (await walk(mediaRoot)).sort(imageSort);
  const grouped = {};

  for (const file of files) {
    const folder = path.posix.dirname(file);
    const packageKey = normalizePackageKey(folder);
    if (!grouped[packageKey]) grouped[packageKey] = [];
    grouped[packageKey].push(`/images/packages/${file}`);
  }

  // Some package folders have descriptive names that are not an exact copy of
  // the package slug. Expose the canonical package/state key as an additional
  // manifest key without moving or duplicating the actual image files.
  const mediaAliases = {
    "multi-state/varanasi-ayodhya-prayagraj-gaya-bodh-gaya": "uttar-pradesh/varanasi-prayagraj-ayodhya",
    "multi-state/varanasi-ayodhya-prayagraj-gaya-bodh-gaya-deoghar": "bihar/bihar-buddhist-circuit",
    "multi-state/delhi-agra-jaipur-golden-triangle": "delhi/delhi-agra-jaipur",

    // Weekend Group Tours stored under multi-state but represented in the
    // package catalogue by their state folders/slugs.
    "goa/goa-weekend-vibe-escape": "multi-state/goa-weekend-group-tour",
    "himachal-pradesh/jibhi-weekend-group-tour": "multi-state/jibhi-weekend-group-tour",
    "himachal-pradesh/kasol-weekend-group-tour": "multi-state/kasol-weekend-group-tour",
    "uttarakhand/kanatal-weekend-group-tour": "multi-state/kanatal-weekend-group-tour",
    "himachal-pradesh/mcleodganj-weekend-group-tour": "multi-state/mcleodganj-weekend-group-tour",
    "rajasthan/udaipur-weekend-group-tour": "multi-state/udaipur-weekend-group-tour",
    "uttarakhand/nainital-weekend-group-tour": "multi-state/nainital-weekend-group-tour",

    // Vaishno Devi package is physically stored under the Jammu & Kashmir
    // image folder while the package catalogue maps the state to "kashmir".
    "kashmir/vaishno-devi-group-yatra": "jammu-kashmir/vaishno-devi-group-yatra",
  };

  for (const [alias, source] of Object.entries(mediaAliases)) {
    if (grouped[source]?.length) grouped[alias] = [...grouped[source]];
  }

  const content = `// AUTO-GENERATED by scripts/generate-package-media.mjs. Do not edit manually.\nexport const packageMedia: Record<string, string[]> = ${JSON.stringify(grouped, null, 2)};\n`;
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, content, "utf8");
  console.log(`Package media manifest generated: ${files.length} image(s), hero-first, with unlimited images and format detection by actual image data.`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});