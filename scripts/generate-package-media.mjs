import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const root = process.cwd();
const output = path.join(root, "data", "packageMedia.ts");
const mediaRoots = [
  { directory: path.join(root, "public", "images", "packages"), urlPrefix: "/images/packages" },
  { directory: path.join(root, "public", "images", "lakshadweep"), urlPrefix: "/images/lakshadweep" },
];

// Package images are discovered from the actual image data, not by a fixed
// filename extension or a fixed number of files. This allows JPG, JPEG, AVIF,
// WebP, PNG and other image formats that Sharp can read.
async function walk(dir, relative = "") {
  if (!fs.existsSync(dir)) return [];
  const result = [];

  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const absolute = path.join(dir, entry.name);
    const rel = path.posix.join(relative, entry.name);

    if (entry.isDirectory()) {
      result.push(...(await walk(absolute, rel)));
      continue;
    }

    try {
      const metadata = await sharp(absolute, { animated: false }).metadata();
      if (metadata.width && metadata.height) result.push(rel);
    } catch {
      // Ignore non-image files such as README/TXT placeholders.
    }
  }

  return result;
}

// Package data uses URL-safe lowercase slugs, while the actual folders may
// use capitals, spaces, underscores or mixed case. Normalize only the
// manifest key; keep the real public URL path unchanged.
function normalizeSegment(value) {
  return value
    .trim()
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function normalizePackageKey(folder) {
  return folder
    .split("/")
    .map(normalizeSegment)
    .filter(Boolean)
    .join("/");
}

const imageSort = (a, b) => {
  const aName = path.posix.basename(a).replace(/\.[^.]+$/, "").toLowerCase();
  const bName = path.posix.basename(b).replace(/\.[^.]+$/, "").toLowerCase();
  const aIsHero = aName === "hero";
  const bIsHero = bName === "hero";

  if (aIsHero && !bIsHero) return -1;
  if (!aIsHero && bIsHero) return 1;
  return a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" });
};

async function main() {
  const grouped = {};
  let totalImages = 0;

  for (const { directory, urlPrefix } of mediaRoots) {
    const files = (await walk(directory)).sort(imageSort);
    totalImages += files.length;

    for (const file of files) {
      const folder = path.posix.dirname(file);
      const packageKey = normalizePackageKey(folder);
      if (!grouped[packageKey]) grouped[packageKey] = [];
      grouped[packageKey].push(`${urlPrefix}/${file}`);
    }
  }

  // Some existing package folders have descriptive names that are not an
  // exact copy of the package slug. Keep those folder names untouched while
  // exposing the canonical package slug as an additional manifest key.
  const mediaAliases = {
    "multi-state/varanasi-ayodhya-prayagraj-gaya-bodh-gaya": "uttar-pradesh/varanasi-prayagraj-ayodhya",
    "multi-state/varanasi-ayodhya-prayagraj-gaya-bodh-gaya-deoghar": "bihar/bihar-buddhist-circuit",
    "multi-state/delhi-agra-jaipur-golden-triangle": "delhi/delhi-agra-jaipur",
    "lakshadweep/lakshadweep-kavaratti-island": "lakshadweep/lakshadweep-kavaratti-island-escape",
    "lakshadweep/lakshadweep-agatti-island": "lakshadweep/lakshadweep-agatti-island-holiday",
    "lakshadweep/lakshadweep-honeymoon": "lakshadweep/romantic-lakshadweep-honeymoon",
    "lakshadweep/lakshadweep-water-sports": "lakshadweep/lakshadweep-lagoon-water-sports-escape",
  };

  for (const [alias, source] of Object.entries(mediaAliases)) {
    if (grouped[source]?.length) grouped[alias] = [...grouped[source]];
  }

  const content = `// AUTO-GENERATED by scripts/generate-package-media.mjs. Do not edit manually.\nexport const packageMedia: Record<string, string[]> = ${JSON.stringify(grouped, null, 2)};\n`;
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, content, "utf8");
  console.log(`Package media manifest generated: ${totalImages} image(s), hero-first, with unlimited images and multi-root format detection.`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
