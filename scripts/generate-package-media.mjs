import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const output = path.join(root, "data", "packageMedia.ts");

// Only actual image formats are indexed. There is intentionally NO file-count limit.
// AVIF is supported; AVI is a video container, not an image format.
const imageExtensions = new Set([
  ".jpg", ".jpeg", ".jpe", ".jfif", ".png", ".webp", ".avif", ".gif",
  ".bmp", ".dib", ".tif", ".tiff", ".svg", ".ico", ".heic", ".heif", ".jxl",
]);

function walk(dir, relative = "") {
  if (!fs.existsSync(dir)) return [];
  const result = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const absolute = path.join(dir, entry.name);
    const rel = path.posix.join(relative, entry.name);
    if (entry.isDirectory()) result.push(...walk(absolute, rel));
    else if (imageExtensions.has(path.extname(entry.name).toLowerCase())) result.push(rel);
  }
  return result;
}

const grouped = {};

function addPackageRoot(mediaRoot, publicPrefix, packageKeyParts) {
  const files = walk(mediaRoot).sort((a, b) => {
    const aName = path.posix.basename(a).toLowerCase();
    const bName = path.posix.basename(b).toLowerCase();
    const aHero = aName.startsWith("hero.") ? 0 : 1;
    const bHero = bName.startsWith("hero.") ? 0 : 1;
    return aHero - bHero || a.localeCompare(b, undefined, { numeric: true });
  });

  for (const file of files) {
    const parts = file.split("/");
    if (parts.length < packageKeyParts) continue;
    const packageFolder = parts.slice(0, packageKeyParts).join("/");
    if (!grouped[packageFolder]) grouped[packageFolder] = [];
    grouped[packageFolder].push(`${publicPrefix}/${file}`);
  }
}

// Existing package media: public/images/packages/<state>/<package-slug>/**
// All nested image folders are included, so hero/gallery-a/gallery-b/etc. are supported.
const packagesRoot = path.join(root, "public", "images", "packages");
if (fs.existsSync(packagesRoot)) {
  for (const stateEntry of fs.readdirSync(packagesRoot, { withFileTypes: true })) {
    if (!stateEntry.isDirectory()) continue;
    const stateDir = path.join(packagesRoot, stateEntry.name);
    for (const packageEntry of fs.readdirSync(stateDir, { withFileTypes: true })) {
      if (!packageEntry.isDirectory()) continue;
      addPackageRoot(path.join(stateDir, packageEntry.name), "/images/packages", 2);
    }
  }
}

// Lakshadweep uploads: public/images/lakshadweep/<package-folder>/**
// Any number of supported image files and any nested gallery folders are included.
const lakshadweepRoot = path.join(root, "public", "images", "lakshadweep");
if (fs.existsSync(lakshadweepRoot)) {
  for (const packageEntry of fs.readdirSync(lakshadweepRoot, { withFileTypes: true })) {
    if (!packageEntry.isDirectory()) continue;
    addPackageRoot(path.join(lakshadweepRoot, packageEntry.name), "/images/lakshadweep", 1);
  }
}

const mediaAliases = {
  "multi-state/varanasi-ayodhya-prayagraj-gaya-bodh-gaya": "uttar-pradesh/varanasi-prayagraj-ayodhya",
  "multi-state/varanasi-ayodhya-prayagraj-gaya-bodh-gaya-deoghar": "bihar/bihar-buddhist-circuit",
  "multi-state/delhi-agra-jaipur-golden-triangle": "delhi/delhi-agra-jaipur",
};

for (const [alias, source] of Object.entries(mediaAliases)) {
  if (grouped[source]?.length) grouped[alias] = [...grouped[source]];
}

const content = `// AUTO-GENERATED by scripts/generate-package-media.mjs. Do not edit manually.\nexport const packageMedia: Record<string, string[]> = ${JSON.stringify(grouped, null, 2)};\n`;
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, content, "utf8");
console.log(`Package media manifest generated with ${Object.values(grouped).reduce((sum, files) => sum + files.length, 0)} image(s). No per-package file limit.`);
