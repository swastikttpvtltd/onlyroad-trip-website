const mk = (x: any) => {
  const base = `/images/packages/multi-state/${x.slug}`;
  return {
    ...x,
    state: x.state || "Multi-State",
    category: x.category || "Jyotirlinga Pilgrimage",
    themes: Array.from(new Set(["Pilgrimage", "Jyotirlinga", ...(x.themes || [])])),
    hero: x.hero || { image: `${base}/hero.jpg`, shortDescription: x.short },
    gallery: x.gallery || [1, 2, 3, 4, 5].map((n) => ({ image: `${base}/gallery${n}.jpg`, alt: `${x.title} – image ${n}` })),
    hotels: [{ name: stay, category: "3-Star", star: "3-Star Hotel" }],
    meals: ["Breakfast", "Dinner"],
    inclusions: [],
    exclusions: [],
    groupSize: x.groupSize || "2-12 Persons",
    difficulty: x.difficulty || "Easy to Moderate",
    quickFacts: {
      pickup: x.pickup || "Delhi / Major Airport / Railway Station",
      drop: x.drop || x.pickup || "Delhi / Major Airport / Railway Station",
      transport: "Private AC Vehicle / Intercity Transfer",
      meals,
      hotelCategory: stay,
      bestSeason: x.bestTime || "October – March",
    },
    customizable: true,
    travelModes: ["Flight + Cab", "Train + Cab", "Private Cab"],
  };
};

